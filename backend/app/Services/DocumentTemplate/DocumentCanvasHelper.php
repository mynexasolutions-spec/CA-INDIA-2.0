<?php

namespace App\Services\DocumentTemplate;

use Dompdf\Canvas;
use Dompdf\FontMetrics;

class DocumentCanvasHelper
{
    /**
     * Draw the rounded outer frame and bottom footer on every page via page_script.
     *
     * @param Canvas $canvas
     * @param FontMetrics $fontMetrics
     * @param array $theme The theme array with 'rgb' float [r, g, b]
     * @param bool $showWatermark Whether watermark is active for this client and document type
     * @param string|null $watermarkText The watermark text to display e.g. "www.abkhanassociates.com"
     * @param int $borderRadius Outer frame border radius in points (11 = rounded for Layout 1, 0 = square for Layout 2)
     */
    public static function attachFrameAndFooter(
        $canvas,
        $fontMetrics,
        array $theme,
        bool $showWatermark = false,
        ?string $watermarkText = null,
        int $borderRadius = 11,
        bool $drawFrame = true
    ): void {
        $font = $fontMetrics->getFont('DejaVu Sans');
        $frameRgb = $theme['rgb'] ?? [0.247, 0.275, 0.314];
        $watermarkText = trim((string) $watermarkText);

        $canvas->page_script(function ($pageNumber, $pageCount, $canvas, $fontMetrics) use (
            $font,
            $frameRgb,
            $showWatermark,
            $watermarkText,
            $borderRadius,
            $drawFrame
        ) {
            // 1. Draw outer frame on canvas (rounded or square) if enabled
            if ($drawFrame) {
                $fw = 1.3;
                $x0 = 18;
                $y0 = 14;
                $x1 = $canvas->get_width() - 18;
                $y1 = $canvas->get_height() - 28;

                if ($borderRadius > 0) {
                    $r = $borderRadius;
                    $canvas->line($x0 + $r, $y0, $x1 - $r, $y0, $frameRgb, $fw);
                    $canvas->line($x0 + $r, $y1, $x1 - $r, $y1, $frameRgb, $fw);
                    $canvas->line($x0, $y0 + $r, $x0, $y1 - $r, $frameRgb, $fw);
                    $canvas->line($x1, $y0 + $r, $x1, $y1 - $r, $frameRgb, $fw);
                    $canvas->arc($x0 + $r, $y0 + $r, $r, $r, 90, 180, $frameRgb, $fw);
                    $canvas->arc($x1 - $r, $y0 + $r, $r, $r, 0, 90, $frameRgb, $fw);
                    $canvas->arc($x1 - $r, $y1 - $r, $r, $r, 270, 360, $frameRgb, $fw);
                    $canvas->arc($x0 + $r, $y1 - $r, $r, $r, 180, 270, $frameRgb, $fw);
                } else {
                    $canvas->line($x0, $y0, $x1, $y0, $frameRgb, $fw);
                    $canvas->line($x0, $y1, $x1, $y1, $frameRgb, $fw);
                    $canvas->line($x0, $y0, $x0, $y1, $frameRgb, $fw);
                    $canvas->line($x1, $y0, $x1, $y1, $frameRgb, $fw);
                }
            }

            // 2. Footer outside frame: darker and slightly larger (tuned)
            $y = $canvas->get_height() - 20;
            $fontSize = 9.2;
            $darkColor = [0.18, 0.22, 0.28];

            // Render watermark text ONLY when $showWatermark is true AND watermark text is not empty
            if ($showWatermark && $watermarkText !== '') {
                $prefix = 'Generated by ';
                $pWidth = $fontMetrics->getTextWidth($prefix, $font, $fontSize);
                $lWidth = $fontMetrics->getTextWidth($watermarkText, $font, $fontSize);
                $lHeight = $fontMetrics->getFontHeight($font, $fontSize);

                $canvas->text(22, $y, $prefix, $font, $fontSize, $darkColor);
                $canvas->text(22 + $pWidth, $y, $watermarkText, $font, $fontSize, $frameRgb);

                // Add clickable link if it looks like a URL or domain
                $linkUrl = preg_match('#^https?://#i', $watermarkText) ? $watermarkText : 'https://' . $watermarkText;
                $canvas->add_link($linkUrl, 22 + $pWidth, $y, $lWidth, $lHeight);
            }

            // Page X of Y (Always displayed on the right)
            $pageText = "Page {$pageNumber} of {$pageCount}";
            $w = $fontMetrics->getTextWidth($pageText, $font, $fontSize);
            $canvas->text($canvas->get_width() - 22 - $w, $y, $pageText, $font, $fontSize, $darkColor);
        });
    }

    /**
     * Resolves the themed PNG icon path for a given theme key and icon name.
     */
    public static function resolveIcons(string $themeKey): array
    {
        $normalizedKey = match ($themeKey) {
            'charcoal' => 'charcoal_grey',
            'plum' => 'dusty_plum',
            default => $themeKey,
        };

        $baseDir = public_path('pdf-assets');
        $themedDir = $baseDir . '/icons/' . $normalizedKey;

        $resolve = function (string $iconName) use ($themedDir, $baseDir) {
            $themed = $themedDir . '/' . $iconName;
            if (file_exists($themed)) {
                return $themed;
            }
            $fallback = $baseDir . '/' . $iconName;
            return file_exists($fallback) ? $fallback : '';
        };

        return [
            'pin' => $resolve('icon2-pin.png'),
            'gstin' => $resolve('icon2-gear.png'),
            'email' => $resolve('icon2-email.png'),
            'phone' => $resolve('icon2-phone.png'),
            'doc' => $resolve('icon2-doc.png'),
            'calendar' => $resolve('icon2-calendar.png'),
            'chart' => $resolve('icon2-chart.png'),
            'reverse' => $resolve('icon2-reverse.png'),
            'rupee' => $resolve('icon-rupee.png'),
            'bank' => $resolve('icon-bank.png'),
            'terms' => $resolve('icon-terms.png'),
        ];
    }
}
