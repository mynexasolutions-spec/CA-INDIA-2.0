<?php

namespace App\Services\DocumentTemplate;

use Dompdf\Canvas;
use Dompdf\FontMetrics;

class DocumentCanvasHelper
{
    /**
     * Draw the rounded outer frame and bottom footer on every page via page_script.
     *
     * @param Canvas $canvas
     * @param FontMetrics $fontMetrics
     * @param array $theme The theme array with 'rgb' float [r, g, b]
     * @param bool $showWatermark Whether watermark is active for this client and document type
     * @param string|null $watermarkText The watermark text to display e.g. "www.abkhanassociates.com"
     * @param int $borderRadius Outer frame border radius in points (11 = rounded for Layout 1, 0 = square for Layout 2)
     */
    public static function attachFrameAndFooter(
        $canvas,
        $fontMetrics,
        array $theme,
        bool $showWatermark = false,
        ?string $watermarkText = null,
        int $borderRadius = 11,
        bool $drawFrame = true,
        int $rightInset = 22,
        bool $mutedFooter = false,
        bool $classicFooter = false,
        float $footerFromBottom = 20,
        ?float $leftInsetOverride = null
    ): void {
        // Classic boxed form (Layout 1): the footer is set in the same black serif as the form itself.
        $font = $fontMetrics->getFont($classicFooter ? 'Times' : 'DejaVu Sans');
        $leftInset = $leftInsetOverride ?? ($classicFooter ? 19 : 22);
        $frameRgb = $theme['rgb'] ?? [0.247, 0.275, 0.314];
        $watermarkText = trim((string) $watermarkText);

        $canvas->page_script(function ($pageNumber, $pageCount, $canvas, $fontMetrics) use (
            $font,
            $frameRgb,
            $showWatermark,
            $watermarkText,
            $borderRadius,
            $drawFrame,
            $rightInset,
            $mutedFooter,
            $classicFooter,
            $leftInset,
            $footerFromBottom
        ) {
            // 1. Draw outer frame on canvas (rounded or square) if enabled
            if ($drawFrame) {
                $fw = 2.4;
                $x0 = 18;
                $y0 = 14;
                $x1 = $canvas->get_width() - 18;
                $y1 = $canvas->get_height() - 28;

                if ($borderRadius > 0) {
                    // four straight edges + four quarter-circle corners made of short solid segments
                    $r = $borderRadius;
                    $canvas->line($x0 + $r, $y0, $x1 - $r, $y0, $frameRgb, $fw);
                    $canvas->line($x0 + $r, $y1, $x1 - $r, $y1, $frameRgb, $fw);
                    $canvas->line($x0, $y0 + $r, $x0, $y1 - $r, $frameRgb, $fw);
                    $canvas->line($x1, $y0 + $r, $x1, $y1 - $r, $frameRgb, $fw);
                    $corner = function (float $cx, float $cy, float $from) use ($r, $canvas, $frameRgb, $fw) {
                        $px = $cx + $r * cos(deg2rad($from));
                        $py = $cy + $r * sin(deg2rad($from));
                        for ($i = 1; $i <= 12; $i++) {
                            $ang = deg2rad($from + (90 * $i / 12));
                            $nx = $cx + $r * cos($ang);
                            $ny = $cy + $r * sin($ang);
                            $canvas->line($px, $py, $nx, $ny, $frameRgb, $fw);
                            [$px, $py] = [$nx, $ny];
                        }
                    };
                    $corner($x1 - $r, $y0 + $r, 270); // top-right
                    $corner($x1 - $r, $y1 - $r, 0);   // bottom-right
                    $corner($x0 + $r, $y1 - $r, 90);  // bottom-left
                    $corner($x0 + $r, $y0 + $r, 180); // top-left
                } else {
                    $canvas->line($x0, $y0, $x1, $y0, $frameRgb, $fw);
                    $canvas->line($x0, $y1, $x1, $y1, $frameRgb, $fw);
                    $canvas->line($x0, $y0, $x0, $y1, $frameRgb, $fw);
                    $canvas->line($x1, $y0, $x1, $y1, $frameRgb, $fw);
                }
            }

            // 2. Footer outside frame: darker and slightly larger (tuned)
            $y = $canvas->get_height() - $footerFromBottom;
            $fontSize = $classicFooter ? 9.6 : 9.2;
            $darkColor = $classicFooter ? [0.07, 0.07, 0.07] : ($mutedFooter ? [0.39, 0.45, 0.55] : [0.18, 0.22, 0.28]);
            // Render watermark text ONLY when $showWatermark is true AND watermark text is not empty
            if ($showWatermark && $watermarkText !== '') {
                $prefix = 'Generated by ';
                $pWidth = $fontMetrics->getTextWidth($prefix, $font, $fontSize);
                $lWidth = $fontMetrics->getTextWidth($watermarkText, $font, $fontSize);
                $lHeight = $fontMetrics->getFontHeight($font, $fontSize);

                $canvas->text($leftInset, $y, $prefix, $font, $fontSize, $darkColor);
                $canvas->text($leftInset + $pWidth, $y, $watermarkText, $font, $fontSize, $frameRgb);

                // Add clickable link if it looks like a URL or domain
                $linkUrl = preg_match('#^https?://#i', $watermarkText) ? $watermarkText : 'https://' . $watermarkText;
                $canvas->add_link($linkUrl, $leftInset + $pWidth, $y, $lWidth, $lHeight);
            }

            // Page X of Y (Always displayed on the right)
            $pageText = "Page {$pageNumber} of {$pageCount}";
            $w = $fontMetrics->getTextWidth($pageText, $font, $fontSize);
            $canvas->text($canvas->get_width() - $rightInset - $w, $y, $pageText, $font, $fontSize, $darkColor);
        });
    }

    /**
     * Page furniture for a layout: frame / corner ribbons plus the footer, in one call so generated invoices and
     * layout previews always look the same.
     *
     *  - Layout 1: classic boxed form — black footer, compact corner ribbons, no canvas frame
     *  - Layout 2: classic form with a letterhead — black footer, large corner ribbons, no canvas frame
     *  - Layout 3: rounded frame in the theme colour
     *  - Layout 4: footer only
     */
    public static function decorate($canvas, $fontMetrics, array $theme, int $layoutId, bool $watermark, ?string $watermarkText): void
    {
        $classic = in_array($layoutId, [1, 2], true);
        // footer link takes the theme colour in every layout (black for 'Simple')
        $footerTheme = $theme;

        // Layout 1: a thin frame right round the page edge, under everything else.
        if ($layoutId === 1) {
            self::attachPageBorder($canvas);
        }

        // Layout 2's bands go down first: the footer text is printed over them, not hidden by them.
        if ($layoutId === 2) {
            self::attachBandRibbons($canvas, $theme);
        }

        self::attachFrameAndFooter(
            $canvas,
            $fontMetrics,
            $footerTheme,
            $watermark,
            $watermarkText,
            $layoutId === 3 ? 16 : ($layoutId === 4 ? 11 : 0),
            $layoutId === 3,
            // Layout 1: keep "Page x of y" clear of the bottom-right corner ribbon; Layout 2: it sits at the form's right edge, over the band
            ($classic && ($theme['key'] ?? '') !== 'simple') ? ($layoutId === 2 ? 54 : 55) : ($classic ? 19 : 22),
            true,
            $classic, // Layouts 1 and 2 share the black serif footer of the printed form
            $layoutId === 2 ? 36 : ($layoutId === 1 ? 33 : 20), // Layout 2: above the bottom band; Layout 1: just under the form (y is the top of the text)
            $layoutId === 2 ? 15 : ($layoutId === 1 ? 17.5 : null)  // Layouts 1 and 2: in line with the form's left edge
        );

        if ($classic && $layoutId !== 2) {
            self::attachRibbons($canvas, $theme, 'compact');
        }
    }

    /**
     * Closed outline of a rounded rectangle as a flat [x1, y1, x2, y2, …] list, for $canvas->polygon().
     *
     * @param float[] $radii top-left, top-right, bottom-right, bottom-left
     */
    public static function roundedRectPoints(float $x, float $y, float $w, float $h, array $radii, int $steps = 10): array
    {
        $max = max(0.0, min($w, $h) / 2);
        [$tl, $tr, $br, $bl] = array_map(fn ($r) => max(0.0, min((float) $r, $max)), $radii);

        $pts = [];
        $arc = function (float $cx, float $cy, float $r, float $from) use (&$pts, $steps) {
            if ($r <= 0) {
                $pts[] = $cx;
                $pts[] = $cy;

                return;
            }
            for ($i = 0; $i <= $steps; $i++) {
                $a = deg2rad($from + 90 * $i / $steps);
                $pts[] = $cx + $r * cos($a);
                $pts[] = $cy + $r * sin($a);
            }
        };

        // clockwise from the top-left corner; y grows downwards
        $arc($x + $tl, $y + $tl, $tl, 180);
        $arc($x + $w - $tr, $y + $tr, $tr, 270);
        $arc($x + $w - $br, $y + $h - $br, $br, 0);
        $arc($x + $bl, $y + $h - $bl, $bl, 90);

        // dompdf's polygon() does not close the path itself, which would leave the final (left) edge undrawn.
        $pts[] = $pts[0];
        $pts[] = $pts[1];

        return $pts;
    }

    /**
     * dompdf paints a CSS border on a rounded box as separate arcs and lines, which pdf.js shows with square corners.
     * Boxes the layout gives a *transparent* border plus a border-radius get their outline drawn here instead, as one
     * closed rounded path, right after the box itself has been rendered. Pass to Dompdf::setCallbacks() BEFORE render().
     */
    public static function roundedBorders(array $theme): array
    {
        $hex = ltrim((string) ($theme['primary'] ?? '#1D40AF'), '#');
        $rgb = [hexdec(substr($hex, 0, 2)) / 255, hexdec(substr($hex, 2, 2)) / 255, hexdec(substr($hex, 4, 2)) / 255];

        // Outlines are collected per page while the document is laid out, then painted by 'paint' once rendering is
        // done, on top of everything: painted inline, table cells inside a box end up covering its side borders.
        $boxes = [];

        // Radius of each rounded box (by class), remembered from its first piece, for pieces of a box that dompdf splits
        // across several pages and that therefore carry no radius of their own.
        $known = [];

        $callbacks = [[
            'event' => 'end_frame',
            'f' => function ($frame, $canvas) use (&$boxes, &$known) {
                $style = $frame->get_style();
                $node = $frame->get_node();
                $key = $node instanceof \DOMElement ? $node->getAttribute('class') : '';
                $isPiece = $frame->is_split || $frame->is_split_off;

                if (! $style->has_border_radius() && ! ($isPiece && isset($known[$key]))) {
                    return;
                }
                // The left border: when dompdf splits a box over a page break it removes the bottom border from the first
                // piece and the top border from the next, but never the side borders.
                $left = $style->get_border_properties()['left'];
                $width = (float) $style->length_in_pt($left['width']);
                if ($left['color'] !== 'transparent' || $width <= 0) {
                    return;
                }

                $box = $frame->get_border_box();
                if ($frame->is_split) {
                    // A box cut at a page break is stretched down towards the page's bottom margin, which would leave a
                    // blank strip inside its outline (and let the outline reach the page frame): end it at the last
                    // thing it actually holds.
                    $content = self::contentBottom($frame);
                    if ($content !== null && $content + $width < $box['y'] + $box['h']) {
                        $box['h'] = $content + $width - $box['y'];
                    }
                }
                $b = [$box['x'], $box['y'], $box['w'], $box['h']];
                if ($style->has_border_radius()) {
                    // top-left, top-right, bottom-right, bottom-left
                    [$tl, $tr, $br, $bl] = $style->resolve_border_radius($b);
                    // dompdf also zeroes the radii on the cut edge: restore them from the opposite edge so every piece is
                    // drawn as a closed rounded card.
                    if ($frame->is_split) {
                        [$br, $bl] = [$tr, $tl];
                    }
                    if ($frame->is_split_off) {
                        [$tl, $tr] = [$bl, $br];
                    }
                    $known[$key] = max($tl, $tr, $br, $bl);
                    $radii = [$tl, $tr, $br, $bl];
                } else {
                    // a middle piece (both edges cut) has lost every radius
                    $radii = array_fill(0, 4, $known[$key]);
                }
                $radii = array_map(fn ($r) => max(0.0, $r - $width / 2), $radii);
                $half = $width / 2;

                $boxes[$canvas->get_page_number()][] = [
                    self::roundedRectPoints($b[0] + $half, $b[1] + $half, $b[2] - $width, $b[3] - $width, $radii),
                    $width,
                ];
            },
        ]];

        // Call with the canvas AFTER render(): page_script() runs at once over the pages that exist by then.
        $paint = function ($canvas) use (&$boxes, $rgb) {
            $canvas->page_script(function ($pageNumber, $pageCount, $canvas) use (&$boxes, $rgb) {
                foreach ($boxes[$pageNumber] ?? [] as [$points, $width]) {
                    $canvas->polygon($points, $rgb, $width);
                }
            });
        };

        return ['callbacks' => $callbacks, 'paint' => $paint];
    }

    /**
     * Lowest edge of the real content a frame holds: its table cells and its text. Containers (the table itself, its
     * rows, divs) are left out on purpose, because when a box is cut at a page break they are stretched down to the
     * page's bottom margin, which is exactly the blank strip this is used to cut off. Null when there is none.
     */
    private static function contentBottom($frame): ?float
    {
        $bottom = null;
        foreach ($frame->get_children() as $child) {
            $node = $child->get_node();
            $isContent = $node instanceof \DOMText
                || ($node instanceof \DOMElement && in_array($node->nodeName, ['td', 'th'], true));
            $box = $child->get_border_box();
            if ($isContent && $box['h'] > 0) {
                $bottom = max($bottom ?? 0.0, $box['y'] + $box['h']);
            }
            $inner = self::contentBottom($child);
            if ($inner !== null) {
                $bottom = max($bottom ?? 0.0, $inner);
            }
        }

        return $bottom;
    }

    /**
     * Layout 1 has two spots where a small nested table (with a vertical divider line between its two columns) sits
     * beside a taller block, in a cell of the outer table:
     *   - the header: the document details (number/date, place of supply/reverse charge, PO/against) beside the
     *     seller block;
     *   - the totals: the tax summary (taxable value ... grand total) beside the amount in words and bank details.
     * dompdf cannot stretch a nested table to its cell's height (a percentage height resolves against the page), so
     * when the neighbouring block is the taller one the divider stopped short of the bottom border. This draws the
     * missing stretch of the line, from where the nested table ends down to the bottom of its cell.
     *
     * Same flow as roundedBorders(): pass 'callbacks' to Dompdf::setCallbacks() BEFORE render(), then call 'paint' with
     * the canvas AFTER render().
     */
    public static function layout1Dividers(): array
    {
        $ink = [17 / 255, 17 / 255, 17 / 255];   // #111111, the layout's grid colour
        $borderPt = 0.75;                         // 1px border
        // [class of the nested table, class of the outer-table cell that holds it]
        $pairs = [['meta-tbl', 'meta-cell'], ['sum', 'right']];
        $state = [];                              // per page and pair: x of the divider, bottom of the nested table
        $lines = [];

        $classesOf = fn ($node) => preg_split('/\s+/', trim($node->getAttribute('class')));
        $insideTable = function ($node, string $tableClass) use ($classesOf) {
            for ($n = $node->parentNode; $n; $n = $n->parentNode) {
                if ($n instanceof \DOMElement && in_array($tableClass, $classesOf($n), true)) {
                    return true;
                }
            }

            return false;
        };

        $callbacks = [[
            'event' => 'end_frame',
            'f' => function ($frame, $canvas) use (&$state, &$lines, $pairs, $classesOf, $insideTable) {
                $node = $frame->get_node();
                if (! $node instanceof \DOMElement) {
                    return;
                }
                $classes = $classesOf($node);
                $page = $canvas->get_page_number();
                $box = $frame->get_border_box();

                foreach ($pairs as $i => [$tableClass, $cellClass]) {
                    if ($node->nodeName === 'td' && in_array('l', $classes, true) && $insideTable($node, $tableClass)) {
                        // the divider is this cell's right border
                        $state[$page][$i]['x'] ??= $box['x'] + $box['w'];
                    } elseif (in_array($tableClass, $classes, true)) {
                        $state[$page][$i]['tableBottom'] = $box['y'] + $box['h'];
                        // 'no-div': the table's last row spans the full width, so there is no divider to continue
                        $state[$page][$i]['skip'] = in_array('no-div', $classes, true);
                    } elseif ($node->nodeName === 'td' && in_array($cellClass, $classes, true)) {
                        $s = $state[$page][$i] ?? [];
                        if (empty($s['skip']) && isset($s['x'], $s['tableBottom']) && $box['y'] + $box['h'] - $s['tableBottom'] > 1.0) {
                            // dompdf centres a collapsed border on the cell edge (half its width each side), so the
                            // line is drawn on the edge itself: it continues the border above it without a jog.
                            $lines[$page][] = [$s['x'], $s['tableBottom'], $box['y'] + $box['h']];
                        }
                    }
                }
            },
        ]];

        $paint = function ($canvas) use (&$lines, $ink, $borderPt) {
            $canvas->page_script(function ($pageNumber, $pageCount, $canvas) use (&$lines, $ink, $borderPt) {
                foreach ($lines[$pageNumber] ?? [] as [$x, $y1, $y2]) {
                    $canvas->line($x, $y1, $x, $y2, $ink, $borderPt);
                }
            });
        };

        return ['callbacks' => $callbacks, 'paint' => $paint];
    }

    /** A thin black frame right round the page edge, on every page (Layout 1). */
    public static function attachPageBorder($canvas): void
    {
        $canvas->page_script(function ($pageNumber, $pageCount, $canvas) {
            $w = 1.6; // line width in points; it is centred on the rectangle, so inset by half of it
            $canvas->rectangle($w / 2, $w / 2, $canvas->get_width() - $w, $canvas->get_height() - $w, [0.067, 0.067, 0.067], $w);
        });
    }

    /**
     * Layout 2's ribbons: a band across the top of every page and another across the bottom, each made of a few
     * slanted pieces in tones of the theme colour, the bottom one rising into a triangle at the right-hand corner.
     * "Simple" has none. The shapes were traced from the approved design on its 1094 x 1438 pixel grid and are scaled
     * to the page, so they stay the same on any paper size.
     */
    public static function attachBandRibbons($canvas, array $theme): void
    {
        if (($theme['key'] ?? '') === 'simple' || empty($theme['rgb'])) {
            return;
        }

        $dark = $theme['ribbon_dark'] ?? $theme['rgb'];
        $light = $theme['ribbon_light'] ?? array_map(fn ($c) => $c + (1 - $c) * 0.55, $dark);
        $mix = fn (array $a, array $b, float $t) => array_map(fn ($x, $y) => $x + ($y - $x) * $t, $a, $b);
        $tone = [
            'dark' => $dark,
            'mid' => $mix($dark, $light, 0.3),
            'light' => $light,
            'lightest' => $mix($light, [1.0, 1.0, 1.0], 0.5),
        ];

        $shapes = [
            // top band: dark block with a slanted right edge, the band running on from it, a lighter stripe under it
            ['dark', [5, 7, 190, 7, 190, 46, 5, 46]],
            ['mid', [190, 7, 334, 7, 293, 46, 190, 46]],
            ['mid', [342, 7, 1094, 7, 1094, 24, 333, 24]],
            ['light', [324, 26, 1094, 26, 1094, 42, 650, 42, 600, 36, 420, 36, 380, 46, 301, 46]],
            ['mid', [5, 49, 200, 49, 200, 60, 5, 60]],
            ['light', [200, 49, 300, 49, 272, 60, 200, 60]],
            // bottom band: two long bars, a slanted block, and the triangle rising at the right-hand corner
            ['lightest', [0, 1403, 905, 1403, 885, 1412, 0, 1412]],
            ['mid', [0, 1415, 500, 1415, 500, 1428, 0, 1428]],
            ['light', [500, 1415, 880, 1415, 852, 1428, 500, 1428]],
            ['light', [840, 1398, 945, 1398, 925, 1428, 820, 1428]],
            // the corner triangle: its slanted edge passes x~1040 at the height of the footer text, so "Page x of y" ends where it begins
            ['mid', [1094, 1358, 1094, 1428, 985, 1428, 1075, 1358]],
            ['light', [1051, 1358, 1065, 1358, 975, 1428, 961, 1428]],
        ];

        $canvas->page_script(function ($pageNumber, $pageCount, $canvas) use ($shapes, $tone) {
            $sx = $canvas->get_width() / 1094;
            $sy = $canvas->get_height() / 1438;
            foreach ($shapes as [$name, $points]) {
                $flat = [];
                for ($i = 0; $i < count($points); $i += 2) {
                    $flat[] = $points[$i] * $sx;
                    $flat[] = $points[$i + 1] * $sy;
                }
                $canvas->polygon($flat, $tone[$name], 0.1, [], true);
            }
        });
    }

    /**
     * Diagonal corner ribbons (top-left and bottom-right) used by Layouts 1 and 2, drawn on every page in the
     * theme colour. The "Simple" colour has no ribbons.
     *
     * @param string $style 'compact' (Layout 1) or 'large' (Layout 2)
     */
    public static function attachRibbons($canvas, array $theme, string $style = 'compact'): void
    {
        if (($theme['key'] ?? '') === 'simple' || empty($theme['rgb'])) {
            return;
        }

        $dark = $theme['ribbon_dark'] ?? $theme['rgb'];
        $light = $theme['ribbon_light'] ?? array_map(fn ($c) => $c + (1 - $c) * 0.55, $dark);

        // Shapes are defined from the top-left corner; the bottom-right corner is the same shape rotated 180 degrees.
        // Compact (Layout 1): a dark triangle plus a lighter stripe parallel to its slanted edge, as on the approved form.
        $shapes = $style === 'large'
            ? [[$light, [0, 0, 96, 0, 0, 76]], [$dark, [0, 0, 68, 0, 0, 54]]]
            : [[$light, [58, 0, 76, 0, 0, 59, 0, 45]], [$dark, [0, 0, 48, 0, 0, 37]]];

        // The large style keeps its full size top-left and a smaller ribbon bottom-right, clear of the signature.
        $bottomScale = $style === 'large' ? 0.85 : 1.0;

        $canvas->page_script(function ($pageNumber, $pageCount, $canvas) use ($shapes, $bottomScale) {
            $w = $canvas->get_width();
            $h = $canvas->get_height();
            foreach (['top-left', 'bottom-right'] as $corner) {
                foreach ($shapes as [$colour, $points]) {
                    $flat = [];
                    for ($i = 0; $i < count($points); $i += 2) {
                        $x = $points[$i];
                        $y = $points[$i + 1];
                        $flat[] = $corner === 'top-left' ? $x : $w - $x * $bottomScale;
                        $flat[] = $corner === 'top-left' ? $y : $h - $y * $bottomScale;
                    }
                    $canvas->polygon($flat, $colour, 0.1, [], true);
                }
            }
        });
    }

    /**
     * Resolves the themed PNG icon path for a given theme key and icon name.
     */
    public static function resolveIcons(string $themeKey): array
    {
        $normalizedKey = match ($themeKey) {
            'charcoal' => 'charcoal_grey',
            'plum' => 'dusty_plum',
            'simple' => 'charcoal_grey',
            default => $themeKey,
        };

        $baseDir = public_path('pdf-assets');
        $themedDir = $baseDir . '/icons/' . $normalizedKey;

        $resolve = function (string $iconName) use ($themedDir, $baseDir) {
            $themed = $themedDir . '/' . $iconName;
            if (file_exists($themed)) {
                return $themed;
            }
            $fallback = $baseDir . '/' . $iconName;
            return file_exists($fallback) ? $fallback : '';
        };

        return [
            'pin' => $resolve('icon2-pin.png'),
            'gstin' => $resolve('icon2-gear.png'),
            'email' => $resolve('icon2-email.png'),
            'phone' => $resolve('icon2-phone.png'),
            'doc' => $resolve('icon2-doc.png'),
            'calendar' => $resolve('icon2-calendar.png'),
            'chart' => $resolve('icon2-chart.png'),
            'reverse' => $resolve('icon2-reverse.png'),
            'rupee' => $resolve('icon-rupee.png'),
            'info' => $resolve('icon-info.png'),
            'bank' => $resolve('icon-bank.png'),
            'terms' => $resolve('icon-terms.png'),
        ];
    }
