    private function buildPdf(array $data, array $theme, array $icons): string
    {
        $pdf = Pdf::loadView('pdf.spike.layout1-spike', [
            'data' => $data,
            'theme' => $theme,
            'icons' => $icons,
        ])
        ->setPaper('a4', 'portrait')
        ->setOption([
            'isRemoteEnabled' => true,
            'dpi' => 96,
            'defaultFont' => 'DejaVu Sans',
        ]);

        $pdf->render();

        $dompdf = $pdf->getDomPDF();
        $canvas = $dompdf->getCanvas();
        $fontMetrics = $dompdf->getFontMetrics();
        $font = $fontMetrics->getFont('DejaVu Sans');

        $frameRgb = $theme['rgb'];

        $canvas->page_script(function ($pageNumber, $pageCount, $canvas, $fontMetrics) use ($font, $frameRgb) {
            // Draw rounded outer frame on canvas
            $fw = 1.3;
            $r = 11;
            $x0 = 18;
            $y0 = 14;
            $x1 = $canvas->get_width() - 18;
            $y1 = $canvas->get_height() - 28;

            $canvas->line($x0 + $r, $y0, $x1 - $r, $y0, $frameRgb, $fw);
            $canvas->line($x0 + $r, $y1, $x1 - $r, $y1, $frameRgb, $fw);
            $canvas->line($x0, $y0 + $r, $x0, $y1 - $r, $frameRgb, $fw);
            $canvas->line($x1, $y0 + $r, $x1, $y1 - $r, $frameRgb, $fw);
            $canvas->arc($x0 + $r, $y0 + $r, $r, $r, 90, 180, $frameRgb, $fw);
            $canvas->arc($x1 - $r, $y0 + $r, $r, $r, 0, 90, $frameRgb, $fw);
            $canvas->arc($x1 - $r, $y1 - $r, $r, $r, 270, 360, $frameRgb, $fw);
            $canvas->arc($x0 + $r, $y1 - $r, $r, $r, 180, 270, $frameRgb, $fw);

            // Footer outside frame: darker and slightly larger (tuned)
            $y = $canvas->get_height() - 20;
            $fontSize = 9.2;
            $darkColor = [0.18, 0.22, 0.28]; // Darker footer text

            $prefix = 'Generated by ';
            $linkText = 'www.abkhanassociates.com';
            $pWidth = $fontMetrics->getTextWidth($prefix, $font, $fontSize);
            $lWidth = $fontMetrics->getTextWidth($linkText, $font, $fontSize);
            $lHeight = $fontMetrics->getFontHeight($font, $fontSize);

            $canvas->text(22, $y, $prefix, $font, $fontSize, $darkColor);
            $canvas->text(22 + $pWidth, $y, $linkText, $font, $fontSize, $frameRgb);
            $canvas->add_link('https://www.abkhanassociates.com', 22 + $pWidth, $y, $lWidth, $lHeight);

            $pageText = "Page {$pageNumber} of {$pageCount}";
            $w = $fontMetrics->getTextWidth($pageText, $font, $fontSize);
            $canvas->text($canvas->get_width() - 22 - $w, $y, $pageText, $font, $fontSize, $darkColor);
        });

        return $pdf->output();
    }

